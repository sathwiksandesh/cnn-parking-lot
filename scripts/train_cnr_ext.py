
from pathlib import Path
import json
import numpy as np
import pandas as pd
import tensorflow as tf

from PIL import Image
from sklearn.model_selection import GroupShuffleSplit
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report
from sklearn.utils.class_weight import compute_class_weight

# --------------------------------------------------
# Configuration
# --------------------------------------------------
SEED = 42
IMAGE_SIZE = (150, 150)
BATCH_SIZE = 32
EPOCHS = 8

MANIFEST = Path("dataset/cnrpark_ext/metadata/cnr_ext_frame_manifest.csv")
MODEL_PATH = Path("models/cnr_ext_cnn.keras")
REPORT_PATH = Path("outputs/reports/cnr_ext_evaluation.json")

tf.keras.utils.set_random_seed(SEED)
MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)

if not MANIFEST.exists():
    raise FileNotFoundError(f"Manifest not found: {MANIFEST}")

df = pd.read_csv(MANIFEST, low_memory=False)
df["frame_path"] = df["frame_path"].astype(str)
df["date_group"] = df["date_group"].astype(str)
df["occupancy"] = df["occupancy"].astype(int)

required = [
    "frame_path", "date_group", "occupancy",
    "x1", "y1", "x2", "y2", "slot_id",
]
missing = [col for col in required if col not in df.columns]
if missing:
    raise ValueError(f"Manifest is missing columns: {missing}")

# --------------------------------------------------
# 1. Verify paths and remove missing records
# --------------------------------------------------
print("Manifest records:", len(df))
print("Checking image paths...")

existing_paths = {
    str(p.resolve())
    for p in Path("dataset/cnrpark_ext/full_images").rglob("*.jpg")
}

# Manifest paths may use Windows separators.
df["local_path"] = df["frame_path"].map(
    lambda value: str(Path(value).resolve())
)

# On Windows, the paths generated by the manifest should match directly.
# This check makes path failures explicit before training.
valid = df["local_path"].isin(existing_paths)
print("Rows with accessible frames:", int(valid.sum()))

if not valid.all():
    examples = df.loc[~valid, "frame_path"].head(5).tolist()
    print("Examples of missing frame paths:", examples)
    raise FileNotFoundError(
        "Some manifest paths do not match extracted local images. "
        "Regenerate the manifest on this computer and rerun."
    )

df["frame_path"] = df["local_path"]
df = df.drop(columns=["local_path"])

# --------------------------------------------------
# 2. Split by date: test dates are never used in training
# --------------------------------------------------
date_table = df[["date_group"]].drop_duplicates().reset_index(drop=True)

first_split = GroupShuffleSplit(
    n_splits=1, test_size=0.20, random_state=SEED
)
train_date_idx, remaining_date_idx = next(
    first_split.split(
        date_table,
        groups=date_table["date_group"],
    )
)

train_dates = set(date_table.iloc[train_date_idx]["date_group"])
remaining_dates = date_table.iloc[remaining_date_idx]["date_group"].to_numpy()

second_split = GroupShuffleSplit(
    n_splits=1, test_size=0.50, random_state=SEED + 1
)
val_date_idx, test_date_idx = next(
    second_split.split(
        np.zeros(len(remaining_dates)),
        groups=remaining_dates,
    )
)

val_dates = set(remaining_dates[val_date_idx])
test_dates = set(remaining_dates[test_date_idx])

train_df = df[df["date_group"].isin(train_dates)].copy()
val_df = df[df["date_group"].isin(val_dates)].copy()
test_df = df[df["date_group"].isin(test_dates)].copy()

assert train_dates.isdisjoint(val_dates)
assert train_dates.isdisjoint(test_dates)
assert val_dates.isdisjoint(test_dates)

for name, part in [
    ("Train", train_df),
    ("Validation", val_df),
    ("Test", test_df),
]:
    print(
        f"{name}: {len(part):,} crops, "
        f"{part['date_group'].nunique()} dates, "
        f"{part['frame_path'].nunique()} frames"
    )
    print("  Labels:", part["occupancy"].value_counts().sort_index().to_dict())

if min(len(train_df), len(val_df), len(test_df)) == 0:
    raise ValueError("A dataset split is empty.")

# --------------------------------------------------
# 3. Crop and preprocess images on demand
# --------------------------------------------------
def crop_generator(frame):
    for row in frame.itertuples(index=False):
        with Image.open(row.frame_path) as source:
            image = source.convert("RGB")
            width, height = image.size

            x1 = max(0, min(int(row.x1), width - 1))
            y1 = max(0, min(int(row.y1), height - 1))
            x2 = max(0, min(int(row.x2), width))
            y2 = max(0, min(int(row.y2), height))

            if x2 <= x1 or y2 <= y1:
                continue

            crop = image.crop((x1, y1, x2, y2))
            crop = crop.resize(IMAGE_SIZE, Image.Resampling.BILINEAR)

            pixels = np.asarray(crop, dtype=np.float32) / 255.0
            label = np.float32(row.occupancy)

            yield pixels, label

def make_dataset(frame, training=False):
    ds = tf.data.Dataset.from_generator(
        lambda: crop_generator(frame),
        output_signature=(
            tf.TensorSpec(shape=(150, 150, 3), dtype=tf.float32),
            tf.TensorSpec(shape=(), dtype=tf.float32),
        ),
    )

    if training:
        ds = ds.shuffle(
            4096, seed=SEED, reshuffle_each_iteration=True
        )

    return ds.batch(BATCH_SIZE).prefetch(tf.data.AUTOTUNE)

train_ds = make_dataset(train_df, training=True)
val_ds = make_dataset(val_df)
test_ds = make_dataset(test_df)

# --------------------------------------------------
# 4. Class weights
# --------------------------------------------------
weights = compute_class_weight(
    class_weight="balanced",
    classes=np.array([0, 1]),
    y=train_df["occupancy"].to_numpy(),
)
class_weights = {
    0: float(weights[0]),
    1: float(weights[1]),
}
print("Class weights:", class_weights)

# --------------------------------------------------
# 5. Build the full-frame CNN
# --------------------------------------------------
inputs = tf.keras.Input(shape=(150, 150, 3))
x = inputs

for filters in (32, 64, 128):
    x = tf.keras.layers.Conv2D(
        filters, 3, padding="same", use_bias=False
    )(x)
    x = tf.keras.layers.BatchNormalization()(x)
    x = tf.keras.layers.Activation("relu")(x)
    x = tf.keras.layers.MaxPooling2D()(x)

x = tf.keras.layers.Conv2D(
    192, 3, padding="same", activation="relu"
)(x)
x = tf.keras.layers.GlobalAveragePooling2D()(x)
x = tf.keras.layers.Dropout(0.35)(x)
x = tf.keras.layers.Dense(64, activation="relu")(x)
x = tf.keras.layers.Dropout(0.2)(x)
outputs = tf.keras.layers.Dense(1, activation="sigmoid")(x)

model = tf.keras.Model(inputs, outputs, name="cnr_ext_occupancy_cnn")

model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
    loss="binary_crossentropy",
    metrics=[
        "accuracy",
        tf.keras.metrics.Precision(name="precision"),
        tf.keras.metrics.Recall(name="recall"),
    ],
)

model.summary()

callbacks = [
    tf.keras.callbacks.ModelCheckpoint(
        str(MODEL_PATH),
        monitor="val_loss",
        save_best_only=True,
        verbose=1,
    ),
    tf.keras.callbacks.EarlyStopping(
        monitor="val_loss",
        patience=3,
        restore_best_weights=True,
        verbose=1,
    ),
    tf.keras.callbacks.ReduceLROnPlateau(
        monitor="val_loss",
        factor=0.5,
        patience=2,
        min_lr=1e-6,
        verbose=1,
    ),
]

# --------------------------------------------------
# 6. Train and evaluate on unseen dates
# --------------------------------------------------
model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=EPOCHS,
    class_weight=class_weights,
    callbacks=callbacks,
)

model = tf.keras.models.load_model(MODEL_PATH)

probabilities = model.predict(test_ds, verbose=1).ravel()
actual = test_df["occupancy"].to_numpy()

# Verify the generator yielded every expected test row.
if len(probabilities) != len(actual):
    raise RuntimeError(
        f"Prediction count ({len(probabilities)}) does not match "
        f"test labels ({len(actual)}). Check crop loading."
    )

predicted = (probabilities >= 0.5).astype(int)
matrix = confusion_matrix(actual, predicted, labels=[0, 1])
report = classification_report(
    actual,
    predicted,
    labels=[0, 1],
    target_names=["free", "busy"],
    output_dict=True,
    zero_division=0,
)

results = {
    "model": "CNR-EXT full-frame crop CNN",
    "seed": SEED,
    "image_size": list(IMAGE_SIZE),
    "split_method": "date-grouped",
    "train_dates": sorted(train_dates),
    "validation_dates": sorted(val_dates),
    "test_dates": sorted(test_dates),
    "train_crops": int(len(train_df)),
    "validation_crops": int(len(val_df)),
    "test_crops": int(len(test_df)),
    "test_accuracy": float(accuracy_score(actual, predicted)),
    "confusion_matrix_rows_true_cols_predicted": matrix.tolist(),
    "classification_report": report,
}

REPORT_PATH.write_text(json.dumps(results, indent=2))

print("\n=== CNR-EXT HELD-OUT TEST RESULTS ===")
print("Accuracy:", f"{results['test_accuracy']:.4%}")
print("Confusion matrix (rows=true, columns=predicted):")
print(matrix)
print(classification_report(
    actual,
    predicted,
    labels=[0, 1],
    target_names=["free", "busy"],
    zero_division=0,
))
print("Model saved:", MODEL_PATH)
print("Report saved:", REPORT_PATH)
